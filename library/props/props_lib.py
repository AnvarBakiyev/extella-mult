# ---------------------------------------------------------------- plants
def _blade(c, x, y, h, lean, w, col):
    c.leafshape(x, y, x + lean, y - h, w, col, bend=lean * 0.08)


def grass_tuft(c, kind):
    r = random.Random(kind)
    cols = [C['leaf'], C['leaf2'], C['leaf3'], C['grass']]
    if kind == 'spiky':
        for k in range(11):
            _blade(c, 180 + k * 15, 420, 160 + r.random() * 120, (k - 5) * 22, 12, cols[k % 3])
    elif kind == 'round':
        for k in range(7):
            c.new(0.8)
            x = 140 + k * 38
            c.ell(x, 380 - (3 - abs(k - 3)) * 30, 46, 80 + (3 - abs(k - 3)) * 20, cols[k % 4])
    elif kind == 'curly':
        for k in range(8):
            x = 170 + k * 25
            c.line(bez((x, 420), (x + (k - 4) * 30, 260), (x + (k - 4) * 60 + 50, 200), (x + (k - 4) * 50 + 20, 250)), cols[k % 3], 14)
    elif kind == 'tall':
        for k in range(9):
            _blade(c, 210 + k * 12, 470, 300 + r.random() * 120, (k - 4) * 14 + r.uniform(-10, 10), 9, cols[k % 3])
    elif kind == 'seeds':
        for k in range(7):
            x = 190 + k * 22
            top = (x + (k - 3) * 30, 140 + r.random() * 60)
            c.line(bez((x, 440), ((x + top[0]) / 2, 300), top), C['olive'], 6)
            c.new(0.7)
            c.ell(top[0], top[1] - 20, 12, 32, C['ochre3'])
            c.new()
        for k in range(8):
            _blade(c, 180 + k * 22, 440, 120 + r.random() * 60, (k - 3.5) * 24, 12, cols[k % 3])
    elif kind == 'low':
        for k in range(16):
            _blade(c, 70 + k * 24, 380, 70 + r.random() * 70, r.uniform(-40, 40), 14, cols[k % 4])
        c.new(0.7)
        c.ell(256, 390, 200, 26, C['leaf2'])


for _k in ('spiky', 'round', 'curly', 'tall', 'seeds', 'low'):
    variant('plants', 'grass_' + _k, grass_tuft, _k)


def _stem(c, x0=256, y0=480, x1=256, y1=220, leaves=True):
    c.line(bez((x0, y0), (x0 + 10, (y0 + y1) / 2), (x1, y1)), C['leaf2'], 14)
    if leaves:
        c.leafshape(x0 + 4, y0 - 90, x0 + 110, y0 - 160, 30, C['leaf'])
        c.leafshape(x0 + 2, y0 - 50, x0 - 100, y0 - 110, 26, C['leaf3'])


def flower(c, kind):
    if kind == 'daisy':
        _stem(c)
        c.new()
