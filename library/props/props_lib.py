def _fruit_round(c, body, hi, cx=256, cy=270, rx=150, ry=140, stem=True, leaf=True, dimple=True):
    c.ell(cx, cy, rx, ry, body)
    if dimple:
        c.ell(cx - rx * 0.3, cy - ry * 0.95, rx * 0.42, ry * 0.18, body)
        c.ell(cx + rx * 0.3, cy - ry * 0.95, rx * 0.42, ry * 0.18, body)
    c.new(0.5)
    c.ell(cx - rx * 0.42, cy - ry * 0.35, rx * 0.22, ry * 0.3, hi)
    if stem:
        c.new(0.6)
        c.line(bez((cx, cy - ry * 0.85), (cx + 4, cy - ry * 1.15), (cx + 22, cy - ry * 1.35)), C['brown2'], 16)
    if leaf:
        c.new(0.7)
        c.leafshape(cx + 14, cy - ry * 1.12, cx + 110, cy - ry * 1.38, 30, C['leaf'], bend=-6)
        c.new(0.3)
        c.line([(cx + 26, cy - ry * 1.16), (cx + 98, cy - ry * 1.34)], C['leaf2'], 4)


