def shade(col, f):
    """Lighten (f > 0) or darken (f < 0) a hex colour by a fraction."""
    col = col.lstrip('#')
    r, g, b = (int(col[i:i + 2], 16) for i in (0, 2, 4))
    if f >= 0:
        r, g, b = (int(v + (255 - v) * f) for v in (r, g, b))
    else:
        r, g, b = (int(v * (1 + f)) for v in (r, g, b))
    return '#%02x%02x%02x' % (r, g, b)


def rot(pts, cx, cy, deg):
    a = math.radians(deg)
    ca, sa = math.cos(a), math.sin(a)
    return [(cx + (x - cx) * ca - (y - cy) * sa, cy + (x - cx) * sa + (y - cy) * ca) for x, y in pts]


def bez(*pts, n=24):
    """Points along a quadratic or cubic bezier."""
    out = []
    for i in range(n + 1):
        t = i / n
        if len(pts) == 3:
            (x0, y0), (x1, y1), (x2, y2) = pts
            out.append(((1 - t) ** 2 * x0 + 2 * (1 - t) * t * x1 + t * t * x2, (1 - t) ** 2 * y0 + 2 * (1 - t) * t * y1 + t * t * y2))
        else:
            (x0, y0), (x1, y1), (x2, y2), (x3, y3) = pts
            u = 1 - t
            out.append((u ** 3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3,
                        u ** 3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3))
    return out


def arcpts(cx, cy, rx, ry, a0, a1, n=40):
    """Points on an ellipse between angles a0..a1 (degrees, 0 = right, 90 = down)."""
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)), cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n)))
            for i in range(n + 1)]


class Canvas:
    """A stack of transparent layers. new() starts a layer; every primitive draws on the current one."""

    def __init__(self, seed=1):
        self.layers = []
        self.rng = random.Random(seed)
        self.new()

    def new(self, depth=1.0):
        if self.layers and self.layers[-1][0].getbbox() is None:
            self.layers.pop()
        img = Image.new('RGBA', (S * SS, S * SS), (0, 0, 0, 0))
        self.layers.append((img, depth))
        self.d = ImageDraw.Draw(img)
        return self

    # all primitives take 512-space coordinates
    def _p(self, pts):
        return [(x * SS, y * SS) for x, y in pts]

    def poly(self, pts, col):
        self.d.polygon(self._p(pts), fill=col)

    def ell(self, cx, cy, rx, ry, col):
        self.d.ellipse([(cx - rx) * SS, (cy - ry) * SS, (cx + rx) * SS, (cy + ry) * SS], fill=col)

    def circ(self, cx, cy, r, col):
        self.ell(cx, cy, r, r, col)

    def rect(self, x0, y0, x1, y1, col, r=0):
        x0, x1 = min(x0, x1), max(x0, x1)
        y0, y1 = min(y0, y1), max(y0, y1)
        if r:
            self.d.rounded_rectangle([x0 * SS, y0 * SS, x1 * SS, y1 * SS], radius=r * SS, fill=col)
        else:
            self.d.rectangle([x0 * SS, y0 * SS, x1 * SS, y1 * SS], fill=col)

    def line(self, pts, col, w, cap=True):
        self.d.line(self._p(pts), fill=col, width=int(w * SS), joint='curve')
        if cap:
            for x, y in (pts[0], pts[-1]):
                self.circ(x, y, w / 2 - 0.3, col)

    def arc(self, cx, cy, rx, ry, a0, a1, col, w):
        self.line(arcpts(cx, cy, rx, ry, a0, a1), col, w)

    def pie(self, cx, cy, r, a0, a1, col):
        self.d.pieslice([(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS], a0, a1, fill=col)

    def ring(self, cx, cy, rx, ry, w, a0, a1, col):
        """A band of width w along an ellipse."""
        o = arcpts(cx, cy, rx, ry, a0, a1)
        i = arcpts(cx, cy, rx - w, ry - w, a0, a1)
        self.poly(o + i[::-1], col)

    def star(self, cx, cy, ro, ri, n, col, deg=-90):
        pts = []
        for k in range(2 * n):
            a = math.radians(deg + 180 * k / n)
            r = ro if k % 2 == 0 else ri
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
        self.poly(pts, col)

    def rrot(self, cx, cy, w, h, deg, col):
        """A rotated rectangle centred at cx, cy."""
        self.poly(rot([(cx - w / 2, cy - h / 2), (cx + w / 2, cy - h / 2), (cx + w / 2, cy + h / 2), (cx - w / 2, cy + h / 2)], cx, cy, deg), col)

    def capsule(self, a, b, w, col):
        self.line([a, b], col, w)

    def blob(self, cx, cy, rx, ry, col, n=7, seed=0, k=0.55):
        """A puffy cloud-like blob made of overlapping circles around an ellipse core."""
        r = random.Random(seed)
        self.ell(cx, cy, rx * 0.8, ry * 0.75, col)
        for i in range(n):
            a = 2 * math.pi * i / n + r.random() * 0.4
            rr = min(rx, ry) * (k + r.random() * 0.2)
            self.circ(cx + (rx - rr) * math.cos(a) * 0.95, cy + (ry - rr) * math.sin(a) * 0.95, rr, col)

    def leafshape(self, x0, y0, x1, y1, wid, col, bend=0.0):
        """A pointed leaf from (x0, y0) to (x1, y1), widest in the middle; bend curves it sideways."""
        mx, my = (x0 + x1) / 2, (y0 + y1) / 2
        dx, dy = x1 - x0, y1 - y0
        L = math.hypot(dx, dy) or 1
        nx, ny = -dy / L, dx / L
        a = (mx + nx * (wid + bend), my + ny * (wid + bend))
        b = (mx - nx * (wid - bend), my - ny * (wid - bend))
        self.poly(bez((x0, y0), a, (x1, y1), n=20) + bez((x1, y1), b, (x0, y0), n=20), col)

    def clip(self):
        """Keep the current layer only where the layer below is drawn (patterns on a body)."""
        img, below = self.layers[-1][0], self.layers[-2][0]
        img.putalpha(Image.composite(img.getchannel('A'), Image.new('L', img.size, 0), below.getchannel('A')))

    def punch(self, cx, cy, rx, ry):
        """Cut an elliptic hole through every layer."""
        for img, _ in self.layers:
            ImageDraw.Draw(img).ellipse([(cx - rx) * SS, (cy - ry) * SS, (cx + rx) * SS, (cy + ry) * SS], fill=(0, 0, 0, 0))

    def frame(self):
        """The finished layers at 512 px."""
        return [(img.resize((S, S), Image.LANCZOS), dep) for img, dep in self.layers if img.getbbox() is not None]


PROPS = {}       # category -> name -> fn(canvas)


def prop(cat, name=None):
    def deco(fn):
        PROPS.setdefault(cat, {})[name or fn.__name__] = fn
        return fn
    return deco


def variant(cat, name, fn, *a, **kw):
    PROPS.setdefault(cat, {})[name] = lambda c: fn(c, *a, **kw)


def draw_prop(name, seed=1):
    for cat, d in PROPS.items():
        if name in d:
            c = Canvas(seed)
            d[name](c)
            return c.frame()
    raise KeyError(name)


def all_props():
    return [(cat, name) for cat, d in PROPS.items() for name in d]


