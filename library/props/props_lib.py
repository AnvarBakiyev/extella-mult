"""Code-drawn felt props: every prop is a Python function that draws one object with Pillow primitives on a
transparent 512x512 canvas, in several layers. Each layer is later turned into a felt cut-out by extella-mult's
felt_composite (bevel lit from the top-left, wool grain, soft shadow on the layers beneath), so a prop made of
3-6 layers gets real depth. No images are loaded, nothing is generated by a model.

Usage:
    from props_lib import PROPS, draw_prop
    layers = draw_prop('apple')          # list of (RGBA 512x512 image, depth)
    PROPS['food']['apple'](canvas)       # the raw drawing function

Coordinates are pixels on the 512 canvas, (0, 0) top-left. Layers are drawn at 2x and downsampled, so edges are
anti-aliased before the felt pass.
"""
