def layout(text):
    """Return list of (glyph strokes in text coords [(x,y)...]) and total width, 1 unit = em height."""
    strokes, x = [], 0.0
    for ch in text:
        g, w = GLYPHS[ch]
        for s in g:
            strokes.append([(x + px, py) for px, py in s])
        x += w
    return strokes, x


def stroke_lengths(strokes):
    out = []
    for s in strokes:
        L = sum(math.hypot(s[i + 1][0] - s[i][0], s[i + 1][1] - s[i][1]) for i in range(len(s) - 1))
        out.append(L)
    return out


def draw_text(ctx, text, x, y, size, color, progress=1.0, width=0.06, slant=0.12):
    """Draw text with its baseline-left at (x,y), em height = size; progress 0..1 reveals the writing. Returns pen tip."""
    strokes, _ = layout(text)
    lens = stroke_lengths(strokes)
    total = sum(lens) or 1.0
    budget = progress * total
    tip = None
    for s, L in zip(strokes, lens):
        if budget <= 0:
            break
        pts = smooth_path(s, 6) if len(s) > 2 else s
        frac = min(1.0, budget / L) if L > 0 else 1.0
        n = max(2, int(len(pts) * frac))
        seg = [(x + (px - (py - B) * slant) * size * ctx.ar, y + (py - B) * size) for px, py in pts[:n]]
        if len(seg) >= 2:
            ctx.line(seg, color, width * size)
        tip = seg[-1]
        budget -= L
    return tip
